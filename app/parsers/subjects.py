"""Разбор колонки «Предметы» из перечня РСОШ.

В колонке через запятую перечислены общеобразовательные предметы и укрупнённые
группы специальностей (УГСН). Проблема: в названиях некоторых УГСН запятая
стоит внутри названия, например
«фотоника, приборостроение, оптические и биотехнические системы и технологии».
Простое деление по запятой разрезает такое название на куски.

Решение: заранее известные составные названия защищаются от деления,
а их сокращённые варианты (они тоже встречаются в перечне) приводятся
к полному каноническому названию.
"""

from __future__ import annotations

import re

PHOTONICS = "фотоника, приборостроение, оптические и биотехнические системы и технологии"

# Опечатки в самих перечнях, которые исправляем до разбора: (шаблон, замена).
# 2023/24: пропущена запятая — «…системы и технологии электроника, радиотехника…».
SOURCE_FIXUPS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"(оптические и биотехнические системы и технологии)\s+(?=электроника)", re.IGNORECASE), r"\1, "),
]

# Составное название (как может встретиться в перечне) -> каноническое название.
COMPOUND_SUBJECTS: dict[str, str] = {
    PHOTONICS: PHOTONICS,
    "фотоника, приборостроение": PHOTONICS,                                          # 2025/26 и позже
    "приборостроение, оптические и биотехнические системы и технологии": PHOTONICS,  # 2022/23
    "электроника, радиотехника и системы связи":
        "электроника, радиотехника и системы связи",
    "прикладная геология, горное дело, нефтегазовое дело и геодезия":
        "прикладная геология, горное дело, нефтегазовое дело и геодезия",
    "прикладная геология, горное дело, нефтегазовое дело":
        "прикладная геология, горное дело, нефтегазовое дело и геодезия",
    "сельское, лесное и рыбное хозяйство":
        "сельское, лесное и рыбное хозяйство",
    "философия, этика и религиоведение":
        "философия, этика и религиоведение",
}

# Одиночные части названия, которые однозначно указывают на всю группу направлений.
# Встречаются в старых перечнях (2022/23): «…инженерные науки, приборостроение, ядерная энергетика…».
SUBJECT_ALIASES: dict[str, str] = {
    "приборостроение": PHOTONICS,
    "оптические и биотехнические системы и технологии": PHOTONICS,
}

# Куски, которые сами по себе не являются предметом: если они остались после
# разбора, значит в перечне появился новый вариант составного названия.
SUSPICIOUS_FRAGMENTS: frozenset[str] = frozenset({
    "радиотехника и системы связи",
    "горное дело",
    "нефтегазовое дело",
    "нефтегазовое дело и геодезия",
    "сельское",
    "лесное и рыбное хозяйство",
    "этика и религиоведение",
})

_PLACEHOLDER = "\x00{}\x00"
_PLACEHOLDER_RE = re.compile(r"\x00(\d+)\x00")

# Самые длинные варианты заменяем первыми, чтобы «фотоника, приборостроение»
# не откусила начало полного названия.
_COMPOUND_ORDER = sorted(COMPOUND_SUBJECTS, key=len, reverse=True)
_COMPOUND_PATTERNS = [
    re.compile(r"(?:^|(?<=,))\s*" + re.escape(name) + r"\s*(?=,|$)", re.IGNORECASE)
    for name in _COMPOUND_ORDER
]


def normalize_text(value: str) -> str:
    """Схлопывает пробелы и обрезает края. Регистр сохраняется («науки о Земле»)."""
    return re.sub(r"\s+", " ", value).strip()


def split_subjects(raw: str) -> tuple[list[str], list[str]]:
    """Делит строку «Предметы» на список.

    Возвращает (предметы, предупреждения). Порядок сохраняется, повторы убираются.
    """
    text = normalize_text(raw)
    if not text:
        return [], []

    for pattern, replacement in SOURCE_FIXUPS:
        text = pattern.sub(replacement, text)

    for index, pattern in enumerate(_COMPOUND_PATTERNS):
        text = pattern.sub(_PLACEHOLDER.format(index), text)

    subjects: list[str] = []
    warnings: list[str] = []
    for part in text.split(","):
        part = part.strip()
        if not part:
            continue
        match = _PLACEHOLDER_RE.fullmatch(part)
        if match:
            part = COMPOUND_SUBJECTS[_COMPOUND_ORDER[int(match.group(1))]]
        part = SUBJECT_ALIASES.get(part.lower(), part)
        if part.lower() in SUSPICIOUS_FRAGMENTS:
            warnings.append(
                f"Подозрительный фрагмент предмета «{part}» в строке «{normalize_text(raw)}»: "
                "возможно, новый вариант составного названия, добавьте его в COMPOUND_SUBJECTS"
            )
        if part not in subjects:
            subjects.append(part)
    return subjects, warnings
